export function resolveAuthLocale(value: string | undefined | null): AuthLocale {
  if (value?.toLowerCase().startsWith("zh")) return "zh";
  if (value?.toLowerCase().startsWith("ru")) return "ru";
  return "en";
}

export function translateValidationMessage(
  locale: AuthLocale,
  message?: string
) {
  if (!message) return undefined;
  const key = validationMessageKeys[message as keyof typeof validationMessageKeys];
  return key ? authCopy[locale].validation[key] : message;
}
